  const packs = { en, fr, de, es, it, nl, pt, hu, ja, zh, ar };

  function normalize(value) {
    const code = String(value || "").toLowerCase().slice(0, 2);
    return CODES.indexOf(code) >= 0 ? code : "en";
  }

  function fill(template, vars) {
    if (!vars) return template;
    return String(template).replace(/\{(\w+)\}/g, function (_, key) {
      return vars[key] == null ? "" : String(vars[key]);
    });
  }

  function translate(lang, key, vars) {
    const pack = packs[normalize(lang)] || packs.en;
    const value = pack[key] != null ? pack[key] : packs.en[key];
    if (value == null) return key;
    return fill(value, vars);
  }

  function readLang() {
    try {
      const saved = localStorage.getItem("apex-lang");
      if (CODES.indexOf(saved) >= 0) return saved;
    } catch (error) { /* keep the browser language */ }
    const nav = (navigator.language || "en").toLowerCase();
    if (nav.indexOf("zh") === 0) return "zh";
    const two = nav.slice(0, 2);
    return CODES.indexOf(two) >= 0 ? two : "en";
  }

  return {
    codes: CODES,
    normalize: normalize,
    localeOf: function (lang) { return LOCALES[normalize(lang)] || "en-GB"; },
    t: translate,
    browser: function () {
      const state = { lang: readLang() };
      function apply(scope) {
        const root = scope || document;
        root.querySelectorAll("[data-i18n]").forEach(function (node) {
          const key = node.getAttribute("data-i18n");
          if (packs[state.lang] && packs[state.lang][key] != null) node.textContent = packs[state.lang][key];
        });
        root.querySelectorAll("[data-i18n-html]").forEach(function (node) {
          const key = node.getAttribute("data-i18n-html");
          if (packs[state.lang] && packs[state.lang][key] != null) node.innerHTML = packs[state.lang][key];
        });
        root.querySelectorAll("[data-i18n-placeholder]").forEach(function (node) {
          const key = node.getAttribute("data-i18n-placeholder");
          if (packs[state.lang] && packs[state.lang][key] != null) node.setAttribute("placeholder", packs[state.lang][key]);
        });
        root.querySelectorAll("[data-i18n-fill]").forEach(function (node) {
          let vars = {};
          try { vars = JSON.parse(node.getAttribute("data-i18n-vars") || "{}"); } catch (error) { vars = {}; }
          node.textContent = translate(state.lang, node.getAttribute("data-i18n-fill"), vars);
        });
        const titleKey = document.body && document.body.getAttribute("data-title");
        if (titleKey && packs[state.lang] && packs[state.lang][titleKey]) document.title = packs[state.lang][titleKey];
        document.documentElement.lang = state.lang === "zh" ? "zh-Hans" : state.lang;
        document.documentElement.dir = state.lang === "ar" ? "rtl" : "ltr";
      }
      return {
        codes: CODES,
        get lang() { return state.lang; },
        locale: LOCALES[state.lang] || "en-GB",
        t: function (key, vars) { return translate(state.lang, key, vars); },
        add: function (extra) {
          Object.keys(extra || {}).forEach(function (code) {
            if (packs[code]) Object.assign(packs[code], extra[code]);
          });
        },
        apply: apply,
        set: function (code) {
          const next = normalize(code);
          try { localStorage.setItem("apex-lang", next); } catch (error) { /* the page still reloads */ }
          location.reload();
        },
      };
    },
  };
